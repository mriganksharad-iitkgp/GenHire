// Render the real landing page offline; verify timing, user control and honest copy.
import assert from 'node:assert/strict';
import {mkdtemp, readFile, writeFile, rm} from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';

const cwd = process.cwd();
const tmp = await mkdtemp(path.join(cwd, '.landing-smoke-'));
assert.ok(path.resolve(tmp).startsWith(path.resolve(cwd)+path.sep));
const dom = new JSDOM('<html><head><meta name="description"></head><body><div id="root"></div></body></html>', {url:'http://localhost:3000', pretendToBeVisual:true});
for (const key of ['window','document','navigator','sessionStorage','localStorage','HTMLElement','Event','MouseEvent','KeyboardEvent','CustomEvent'])
  Object.defineProperty(globalThis,key,{value:dom.window[key],configurable:true});
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const media = {matches:false,addEventListener(_,fn){this.update=fn;},removeEventListener(){}};
window.matchMedia = () => media;
const catalog = {credits:{practice_interview:30,practice_interview_proctored:50,candidate_invite:1,signup_bonus:100,mock_oa:30,oa_setup:30,oa_attempt:30},packs:{},currency:'INR'};
let pricingFails = false;
globalThis.fetch = async () => new Response(JSON.stringify(pricingFails?{}:catalog),{status:pricingFails?503:200,headers:{'Content-Type':'application/json'}});
const React = await import('react');
const {act} = React;
const {createRoot} = await import('react-dom/client');
const {MemoryRouter} = await import('react-router-dom');
const intervals = new Map();
const nativeSetInterval = globalThis.setInterval, nativeClearInterval = globalThis.clearInterval;
let sequence = 0, root;
globalThis.setInterval = (fn,ms) => { const id=++sequence; intervals.set(id,{fn,ms}); return id; };
globalThis.clearInterval = id => intervals.delete(id);
const button = name => [...document.querySelectorAll('button')].find(b=>b.textContent.trim().endsWith(name));
const click = async node => { assert.ok(node); await act(async()=>node.dispatchEvent(new MouseEvent('click',{bubbles:true}))); };
const selected = () => document.querySelector('button[aria-label^="Step"][aria-pressed="true"]');
let passed = 0;
try {
  const result = await build({stdin:{contents:'export {default} from "features/landing/pages/LandingPage";',resolveDir:cwd,loader:'jsx'},bundle:true,write:false,outfile:path.join(tmp,'page.mjs'),platform:'node',format:'esm',packages:'external',alias:{features:path.join(cwd,'src/features'),shared:path.join(cwd,'src/shared')},loader:{'.js':'jsx'},define:{'process.env':JSON.stringify({NODE_ENV:'test',REACT_APP_API_URL:'http://localhost:5000'})},plugins:[{name:'css',setup(plugin){plugin.onLoad({filter:/\.css$/},async({path:file})=>({contents:await readFile(file,'utf8'),loader:'local-css'}));}}]});
  await writeFile(path.join(tmp,'page.mjs'),result.outputFiles.find(f=>f.path.endsWith('.mjs')).text);
  const Landing = (await import(pathToFileURL(path.join(tmp,'page.mjs')))).default;
  const mount = async () => { root=createRoot(document.getElementById('root')); await act(async()=>root.render(React.createElement(MemoryRouter,null,React.createElement(Landing)))); };
  await mount();
  assert.match(document.querySelector('h1').textContent,/Screen with AI/);
  assert.match(document.body.textContent,/coding, SQL and MCQ/i);
  assert.doesNotMatch(document.body.textContent,/10K\+|TechCorp|unlimited interviews|only when a session completes successfully/);
  assert.equal(document.querySelectorAll('main').length,1);
  for (const anchor of document.querySelectorAll('a[href^="#"]')) assert.ok(document.getElementById(anchor.hash.slice(1)),anchor.href);
  passed++;
  assert.equal(intervals.size,1);
  const timer = [...intervals.values()][0];
  assert.equal(timer.ms,2000);
  await act(async()=>timer.fn());
  assert.match(selected().textContent,/Complete AI screening/);
  await click(document.querySelector('button[aria-label^="Step 3"]'));
  assert.match(selected().textContent,/Take an OA/);
  assert.equal(intervals.size,0);
  await click(button('Resume animation'));
  assert.equal(intervals.size,1);
  await click(button('Pause animation'));
  assert.equal(intervals.size,0);
  await click(button('For Recruiters'));
  assert.match(selected().textContent,/Design the role/);
  passed++;
  await click(button('Resume animation'));
  await act(async()=>{media.matches=true;media.update();});
  assert.equal(intervals.size,0);
  assert.ok(!button('Pause animation'));
  await click(document.querySelector('button[aria-label^="Step 4"]'));
  assert.match(selected().textContent,/Review & arrange/);
  passed++;
  const toggle = document.getElementById('landing-menu-toggle');
  assert.equal(toggle.getAttribute('aria-expanded'),'false');
  assert.ok(document.getElementById('landing-mobile-menu').hasAttribute('inert'));
  await click(toggle);
  assert.equal(toggle.getAttribute('aria-expanded'),'true');
  await act(async()=>document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true})));
  assert.equal(toggle.getAttribute('aria-expanded'),'false');
  assert.equal(document.activeElement,toggle);
  passed++;
  await act(async()=>root.unmount()); root=null;
  pricingFails=true; await mount();
  assert.ok(button('Retry current prices'));
  pricingFails=false; await click(button('Retry current prices'));
  assert.ok(!button('Retry current prices'));
  assert.match(document.querySelector('meta[name="description"]').content,/online assessments/);
  passed++;
  console.log(`Landing smoke: ${passed} checks passed (copy, 2s timer/pause, reduced motion, menu, pricing retry).`);
} finally {
  if(root) await act(async()=>root.unmount());
  globalThis.setInterval=nativeSetInterval; globalThis.clearInterval=nativeClearInterval;
  dom.window.close();
  await rm(tmp,{recursive:true,force:true});
}
